// Builds the FLEXD logo files from the client's crown-and-mask artwork (on transparency):
// public/brand/flexd-mark-<fingerprint>.webp (720x480; also the chest lid's inlay mask, through its
// alpha; its name goes to src/config/mark-file.ts, so the image optimiser and browsers never serve an
// older logo) and src/app/icon.png (512) / src/app/apple-icon.png (180), the mark on the ground colour.
// Run from flexd/: npm run brand:assets -- <artwork.png|webp> [--tint]
// --tint recolours the artwork into the lilac chrome of the client's screens (see AMETHYST).
// Without a file it keeps the current mark and redraws the icons from it.
import { createHash } from "node:crypto";
import { readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const at = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const BRAND = at("public/brand");
const SIZE = { width: 720, height: 480 };
const GROUND = "#0A0510";
const CLEAR = { r: 0, g: 0, b: 0, alpha: 0 };

// The mark's tones in the client's screens, darkest to brightest, by share of the mark's pixels
// (sampled from the age-gate screen and matched by eye, 2026-10-15).
const AMETHYST = [
  [0, "#1f0733"],
  [0.04, "#431a63"],
  [0.12, "#622d84"],
  [0.25, "#8047a3"],
  [0.4, "#9d63ba"],
  [0.55, "#ba86d1"],
  [0.68, "#d5a9e6"],
  [0.8, "#ebc9f6"],
  [0.9, "#f9e3fc"],
  [1, "#ffffff"],
].map(([share, hex]) => [share, [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16))]);

function ramp(q) {
  const hi = AMETHYST.findIndex(([share]) => share >= q);
  if (hi <= 0) return AMETHYST[0][1];
  const [a, ca] = AMETHYST[hi - 1];
  const [b, cb] = AMETHYST[hi];
  const t = (q - a) / (b - a);
  return ca.map((c, i) => Math.round(c + (cb[i] - c) * t));
}

/** Keeps the artwork's shape and shading; each pixel takes the tone at its brightness rank. */
async function tint(file) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const lum = (i) => Math.round(0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2]);
  const count = new Array(256).fill(0);
  let total = 0;
  for (let i = 0; i < data.length; i += 4) {
    if (data[i + 3] > 200) {
      count[lum(i)]++;
      total++;
    }
  }
  const rank = [];
  for (let v = 0, below = 0; v < 256; below += count[v], v++) rank[v] = (below + count[v] / 2) / total;
  for (let i = 0; i < data.length; i += 4) {
    if (data[i + 3] > 0) [data[i], data[i + 1], data[i + 2]] = ramp(rank[lum(i)]);
  }
  return sharp(data, { raw: info }).png().toBuffer();
}

const marks = async () => (await readdir(BRAND)).filter((f) => f.startsWith("flexd-mark"));
const artwork = process.argv[2];
let name = (await marks())[0];
if (artwork) {
  const source = process.argv.includes("--tint") ? await tint(artwork) : artwork;
  const trimmed = await sharp(source).ensureAlpha().trim({ threshold: 8 }).toBuffer();
  const webp = await sharp(trimmed)
    .resize({ ...SIZE, fit: "contain", background: CLEAR })
    .webp({ quality: 92, alphaQuality: 100 })
    .toBuffer();
  name = `flexd-mark-${createHash("sha256").update(webp).digest("hex").slice(0, 8)}.webp`;
  for (const old of await marks()) await rm(join(BRAND, old));
  await writeFile(join(BRAND, name), webp);
  await writeFile(
    at("src/config/mark-file.ts"),
    `/** Generated by scripts/make-brand-assets.mjs: the logo raster's fingerprinted file name in public/brand. */
export const LOGO_FILE = "${name}";
`,
  );
}
if (!name) throw new Error("no logo in public/brand yet: pass the artwork file");
const MARK = join(BRAND, name);

async function icon(size, file) {
  const room = Math.round(size * 0.84);
  const mark = await sharp(MARK).resize({ width: room, height: room, fit: "inside" }).toBuffer();
  await sharp({ create: { width: size, height: size, channels: 4, background: GROUND } })
    .composite([{ input: mark, gravity: "center" }])
    .png({ palette: true, quality: 95, effort: 10 }) // the tab icon loads on every page
    .toFile(at(file));
}

await icon(512, "src/app/icon.png");
await icon(180, "src/app/apple-icon.png");
console.log(`${artwork ? `wrote public/brand/${name}, src/config/mark-file.ts, ` : ""}src/app/icon.png, src/app/apple-icon.png`);
