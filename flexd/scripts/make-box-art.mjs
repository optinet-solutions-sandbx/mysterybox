// Cuts the FLEXD box out of the client's first screen (the 592x1280 "The Time Room" screen) into
// public/boxes/flexd-box-<fingerprint>.webp: the box with a soft patch of its glossy floor, on
// transparency, enlarged. Its file name, size, lid seam and light origin go to
// src/components/chest/box-art.ts. Run from flexd/: npm run box:art -- <screen.png>
// The outline is in that screen's pixels; a sharper export of the same screen only needs SOURCE_WIDTH.
import { createHash } from "node:crypto";
import { readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const at = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const SOURCE_WIDTH = 592;
/** The part of the screen kept, and the box's outline, lid seam and lid centre within the screen. */
// The screen's carousel dots start at y 545, so the region stops above them.
const REGION = { left: 60, top: 180, width: 510, height: 362 };
const OUTLINE = [[93.3, 259.3], [270, 193.3], [534, 239.3], [531.3, 433.3], [380, 514], [100, 415]];
const FLOOR = [[100, 415], [380, 514], [531.3, 433.3], [540, 462], [380, 536], [92, 448]];
const SEAM = [[93.3, 300], [206.7, 331.7], [250, 348.3], [380, 388.3], [532.7, 304]];
const LID_CENTRE = [319, 254.5];
/** The body's back-left top corner, hidden under the lid: with the seam it outlines the open box's mouth. */
const BACK_CORNER = [270, 232];
const SCALE = 2;

const file = process.argv[2];
if (!file) throw new Error("pass the client's first screen: npm run box:art -- <screen.png>");
const meta = await sharp(file).metadata();
const k = meta.width / SOURCE_WIDTH;
const W = REGION.width * SCALE;
const H = REGION.height * SCALE;
const px = ([x, y]) => [((x - REGION.left) * SCALE).toFixed(1), ((y - REGION.top) * SCALE).toFixed(1)];
const points = (list) => list.map((p) => px(p).join(",")).join(" ");
const unit = ([x, y]) => [+((x - REGION.left) / REGION.width).toFixed(4), +((y - REGION.top) / REGION.height).toFixed(4)];

const mask = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">
<defs>
  <filter id="floor" x="-20%" y="-20%" width="140%" height="160%"><feGaussianBlur stdDeviation="16"/></filter>
  <filter id="edge"><feGaussianBlur stdDeviation="0.7"/></filter>
</defs>
<polygon points="${points(FLOOR)}" fill="#fff" fill-opacity="0.8" filter="url(#floor)"/>
<polygon points="${points(OUTLINE)}" fill="#fff" filter="url(#edge)"/>
</svg>`;

const art = await sharp(file)
  .extract({
    left: Math.round(REGION.left * k),
    top: Math.round(REGION.top * k),
    width: Math.round(REGION.width * k),
    height: Math.round(REGION.height * k),
  })
  .resize(W, H, { kernel: "lanczos3" })
  .sharpen({ sigma: 0.9, m1: 0.6, m2: 1.4 })
  .ensureAlpha()
  .composite([{ input: Buffer.from(mask), blend: "dest-in" }])
  .webp({ quality: 90, alphaQuality: 100, effort: 6 })
  .toBuffer();

const dir = at("public/boxes");
const name = `flexd-box-${createHash("sha256").update(art).digest("hex").slice(0, 8)}.webp`;
for (const old of await readdir(dir)) if (old.endsWith(".webp")) await rm(join(dir, old));
await writeFile(join(dir, name), art);
await writeFile(
  at("src/components/chest/box-art.ts"),
  `/** Generated by scripts/make-box-art.mjs: the box picture cut from the client's first screen. */
export const BOX_ART = {
  src: "/boxes/${name}",
  width: ${W},
  height: ${H},
  /** The lid seam, left to right, as fractions of the picture (the lid lifts off along it). */
  seam: ${JSON.stringify(SEAM.map(unit))},
  /** Centre of the lid, where the light comes out. */
  lid: ${JSON.stringify(unit(LID_CENTRE))},
  /** The body's back-left top corner (under the lid); with the seam it outlines the open box's mouth. */
  back: ${JSON.stringify(unit(BACK_CORNER))},
} as const;
`,
);
console.log(`wrote public/boxes/${name} (${W}x${H}, ${art.length} bytes) and src/components/chest/box-art.ts`);
