"""Trim transparent margins from product cut-outs and record their aspect ratios.

Usage (repo root):  python scripts/normalize_product_images.py web/public/reference/misty web/src/data/image-meta.ts

ItemArt sizes every image to the same visual area from these ratios, so a thin bracelet and a
tall watch read at a consistent size next to a bag.
"""
import sys
from pathlib import Path

from PIL import Image

src = Path(sys.argv[1])
out_ts = Path(sys.argv[2])

aspects: dict[str, float] = {}
for f in sorted(src.glob("*.webp")):
    im = Image.open(f).convert("RGBA")
    bbox = im.getchannel("A").point(lambda a: 255 if a > 10 else 0).getbbox()
    if bbox:
        pad = max(2, round(max(im.size) * 0.015))
        x0, y0, x1, y1 = bbox
        crop = (max(x0 - pad, 0), max(y0 - pad, 0), min(x1 + pad, im.width), min(y1 + pad, im.height))
        if crop != (0, 0, im.width, im.height):
            im = im.crop(crop)
            im.save(f, "WEBP", quality=86, method=6)
    aspects[f.stem] = round(im.width / im.height, 3)

lines = [
    "/**",
    " * Width/height of each trimmed product cut-out. Generated by",
    " * scripts/normalize_product_images.py; do not edit by hand.",
    " */",
    "export const imageAspect: Record<string, number> = {",
]
lines += [f'  "{k}": {v},' for k, v in aspects.items()]
lines += ["};", ""]
out_ts.write_text("\n".join(lines), encoding="utf-8")
print(len(aspects), "images; aspect range", min(aspects.values()), "-", max(aspects.values()))
