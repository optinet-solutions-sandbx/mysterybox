"""Render a site's chest finishes to transparent WebP stills (<app>/public/boxes/<finish>-<fingerprint>.webp).

The stills are the first paint of every <Chest> and the image used in grids; they must come from
the same WebGL model, so rerun this after changing <app>/src/components/chest/chest-scene.ts (or,
in flexd/, chest-finishes.ts).

Usage (that app's dev server running, e.g. `cd play && npm run dev`):
    python scripts/render_box_stills.py [base_url] [app]      # app: play (default) or flexd
"""
import base64
import hashlib
import io
import sys
from pathlib import Path

from PIL import Image
from playwright.sync_api import sync_playwright

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:3000"
APP = sys.argv[2] if len(sys.argv) > 2 else "play"
ROOT = Path(__file__).resolve().parent.parent
if not (ROOT / APP / "package.json").exists():
    sys.exit(f"no app folder {ROOT / APP}")
OUT = ROOT / APP / "public" / "boxes"
VERSION_FILE = ROOT / APP / "src" / "components" / "chest" / "stills-version.ts"
OUT.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(args=["--use-angle=swiftshader", "--enable-unsafe-swiftshader"])
    page = browser.new_page(viewport={"width": 1200, "height": 1200}, device_scale_factor=1)
    page.goto(BASE + "/dev/stills")
    page.wait_for_function("window.__stillsReady === true", timeout=120_000)
    stills = page.evaluate("window.__stills")
    browser.close()

# File names carry a fingerprint of this render, so browsers and the image optimiser never serve
# an older chest after a re-render (src/components/chest/stills-version.ts holds the current one).
encoded = {}
for finish, url in stills.items():
    img = Image.open(io.BytesIO(base64.b64decode(url.split(",", 1)[1]))).convert("RGBA")
    img = img.resize((880, 880), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "WEBP", quality=90, method=6)
    encoded[finish] = buf.getvalue()
version = hashlib.sha1(b"".join(encoded[f] for f in sorted(encoded))).hexdigest()[:8]
for old_file in OUT.glob("*.webp"):
    old_file.unlink()
for finish, data in encoded.items():
    (OUT / f"{finish}-{version}.webp").write_bytes(data)
    print("wrote", OUT / f"{finish}-{version}.webp")
VERSION_FILE.write_text(
    "/** Generated by scripts/render_box_stills.py: the fingerprint in the chest stills' file names. */\n"
    f'export const STILLS_VERSION = "{version}";\n',
    encoding="utf-8",
)
print("version", version)
